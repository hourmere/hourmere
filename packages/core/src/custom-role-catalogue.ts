export type CustomRolePermission =
  | (typeof customRoleCatalogueV1.phaseOne)[number]
  | (typeof customRoleCatalogueV1.phaseTwoPersonalData)[number]

const customRolePermissionsV1: ReadonlySet<string> = new Set([
  ...customRoleCatalogueV1.phaseOne,
  ...customRoleCatalogueV1.phaseTwoPersonalData,
])

export function isCustomRolePermission(version: number, id: string): id is CustomRolePermission {
  return version === customRoleCatalogueV1.version && customRolePermissionsV1.has(id)
}
