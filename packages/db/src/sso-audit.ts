export type SsoAuditDetailKey =
  | 'method'
  | 'providerId'
  | 'revision'
  | 'outcome'
  | 'reason'
  | 'correlationId'

interface DetailSpec {
  readonly required: readonly SsoAuditDetailKey[]
  readonly optional: readonly SsoAuditDetailKey[]
  readonly outcomes?: readonly string[]
}

