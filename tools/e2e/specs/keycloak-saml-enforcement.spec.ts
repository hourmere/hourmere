import { inflateRawSync } from 'node:zlib'
import { DOMParser } from '@xmldom/xmldom'
import {
  button,
  clickPrivate,
  completeSamlCeremony,
  emailLinkLabel,
  expectMailboxCannotEnterTeam,
  samlClient,
  samlSignInUrl,
  signInThroughSaml,
  ssoLabel,
  submitKeycloakLogin,
} from '../keycloak/browser.ts'
import { exerciseTeamDelegation, expectEnforcedTeamAccess } from '../keycloak/enforcement.ts'
import { expect, test } from '../keycloak/fixture.ts'

test.use({ protocol: 'saml', oidcEnabled: false, enforced: true })

function requestsFreshAuthentication(authorization: URL) {
  const encodedRequest = authorization.searchParams.get('SAMLRequest')
  if (!encodedRequest) throw new Error('The Keycloak redirect did not carry an AuthnRequest')
  try {
    // Inspect only the AuthnRequest generated by the local service provider.
    const xml = inflateRawSync(Buffer.from(encodedRequest, 'base64'), {
      maxOutputLength: 16 * 1024,
    }).toString('utf8')
    const request = new DOMParser({
      onError: () => {
        throw new Error('Invalid fixture AuthnRequest')
      },
    }).parseFromString(xml, 'application/xml').documentElement
    return (
      request?.localName === 'AuthnRequest' &&
      request.namespaceURI === 'urn:oasis:names:tc:SAML:2.0:protocol' &&
      request.getAttribute('ForceAuthn') === 'true'
    )
  } catch {
    throw new Error('The local service provider sent a malformed AuthnRequest')
  }
}

test.describe('with SAML injected into the fixture', () => {
  test.use({ samlEnabled: true })

  test('refuses a mailbox session at the team boundary and admits the same owner through SAML', async ({
    page,
    keycloak: app,
  }) => {
    await samlClient(app).setSignAssertions(true)
    await expectEnforcedTeamAccess(page, app, samlSignInUrl(app), signInThroughSaml)
  })

  test('binds a CLI and MCP lease only after ForceAuthn SAML step-up and revokes it', async ({
    page,
    context,
    keycloak: app,
  }) => {
    const client = samlClient(app)
    await client.setSignAssertions(true)
    await exerciseTeamDelegation(page, app, signInThroughSaml, async () => {
      const endpoint = new URL(client.ssoEndpoint)
      // The same BrowserContext still holds a Keycloak session from the initial sign-in.
      const [popup, redirect] = await Promise.all([
        context.waitForEvent('page'),
        context.waitForEvent('request', {
          predicate: (request) => {
            const url = new URL(request.url())
            return (
              request.method() === 'GET' &&
              url.origin === endpoint.origin &&
              url.pathname === endpoint.pathname
            )
          },
        }),
        clickPrivate(page.getByRole('link', { name: /^Open identity provider/ })),
      ])
      try {
        expect(
          requestsFreshAuthentication(new URL(redirect.url())),
          'The SAML step-up request must include ForceAuthn="true"',
        ).toBe(true)
        await submitKeycloakLogin(popup, app, app.idp.linked.username)
        const completion = await completeSamlCeremony(popup, app)
        expect(completion.status()).toBe(303)
        expect((await completion.headerValue('location')) === '/app/settings').toBe(true)
        await expect(popup.getByRole('heading', { name: 'Account', exact: true })).toBeVisible()
      } finally {
        await popup.close()
      }
    })
  })
})

test('without SAML injection the seeded team still enforces SSO and offers no SAML sign-in', async ({
  page,
  keycloak: app,
}) => {
  const [instance] = await Promise.all([
    page.waitForResponse((response) => response.url() === `${app.url}/api/v1/instance`),
    page.goto(samlSignInUrl(app)),
  ])
  expect(instance.status()).toBe(200)
  expect(await instance.json()).toMatchObject({ ssoOidcEnabled: false, ssoSamlEnabled: false })
  await expect(button(page, emailLinkLabel)).toBeVisible()
  await expect(button(page, ssoLabel)).toHaveCount(0)
  await expectMailboxCannotEnterTeam(page, app)
})
