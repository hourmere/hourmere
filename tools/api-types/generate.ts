// Writes the web app's API types from the published product OpenAPI document and the
// browser authentication contracts. Run with `npm run api:types` after changing a route.
//
// This is its own workspace because openapi-typescript builds the types with TypeScript's
// JavaScript compiler API, which TypeScript 7 (the repository's compiler) no longer ships:
// it gets TypeScript 5 here without changing the `tsc` the other workspaces use. That
// TypeScript 5 is only openapi-typescript's: this file is checked by the root's TypeScript 7
// (`npm run typecheck` runs `tsc -p tools/api-types`), since the server code it imports needs
// TypeScript 7's Temporal types.
import { writeFile } from 'node:fs/promises'
import openapiTS, { astToString, type OpenAPI3, type SchemaObject } from 'openapi-typescript'
import { openApiDocument } from '../../apps/server/src/openapi-document.ts'
import {
  MAILBOX_PROOF_CONSUME_PATH,
  MAILBOX_PROOF_SEND_PATH,
  MailboxProofConsumeInput,
  MailboxProofSendInput,
} from '../../apps/server/src/sso-mailbox-proof.ts'
import { OIDC_SIGN_IN_PATH, OidcSignInInput } from '../../apps/server/src/sso-oidc-sign-in.ts'

// Authentication ceremonies are outside the published product API and its parity inventory.
// Extend the web client's declaration from the inputs the existing auth handlers validate.
function authPost(
  input: { toJSONSchema(): unknown },
  status: number,
  properties: Record<string, SchemaObject>,
) {
  const json = (schema: SchemaObject) => ({
    'application/json': { schema },
  })
  const object = (properties: Record<string, SchemaObject>): SchemaObject => ({
    type: 'object',
    properties,
    required: Object.keys(properties),
  })
  return {
    post: {
      requestBody: { required: true, content: json(input.toJSONSchema() as SchemaObject) },
      responses: {
        [status]: { description: 'Success', content: json(object(properties)) },
        default: { description: 'Error', content: json(object({ error: { type: 'string' } })) },
      },
    },
  }
}

const authPaths = {
  [MAILBOX_PROOF_SEND_PATH]: authPost(MailboxProofSendInput, 202, {
    status: { type: 'string', const: 'queued' },
  }),
  [MAILBOX_PROOF_CONSUME_PATH]: authPost(MailboxProofConsumeInput, 200, {
    status: { type: 'string', const: 'proven' },
  }),
  [OIDC_SIGN_IN_PATH]: authPost(OidcSignInInput, 200, {
    url: { type: 'string', format: 'uri' },
    redirect: { type: 'boolean', const: true },
  }),
}

const out = new URL('../../apps/web/src/api/schema.d.ts', import.meta.url)
const doc = (await openApiDocument()) as OpenAPI3
const ast = await openapiTS(
  { ...doc, paths: { ...doc.paths, ...authPaths } },
  { alphabetize: true },
)
const header = `/**
 * Generated by \`npm run api:types\` from the product OpenAPI document and browser auth contracts.
 * Do not edit: change the server contracts and regenerate.
 */

`
await writeFile(out, header + astToString(ast))
console.log(`wrote ${out.pathname}`)
