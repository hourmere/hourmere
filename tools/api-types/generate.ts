// Writes the web app's API types (apps/web/src/api/schema.d.ts) from the OpenAPI document
// the server publishes. Run with `npm run api:types` after changing a route; CI regenerates
// the file and fails if it differs from the committed one.
//
// This is its own workspace because openapi-typescript builds the types with TypeScript's
// JavaScript compiler API, which TypeScript 7 (the repository's compiler) no longer ships:
// it gets TypeScript 5 here without changing the `tsc` the other workspaces use. That
// TypeScript 5 is only openapi-typescript's: this file is checked by the root's TypeScript 7
// (`npm run typecheck` runs `tsc -p tools/api-types`), since the server code it imports needs
// TypeScript 7's Temporal types.
import { writeFile } from 'node:fs/promises'
import openapiTS, { astToString, type OpenAPI3 } from 'openapi-typescript'
import { openApiDocument } from '../../apps/server/src/openapi-document.ts'

const out = new URL('../../apps/web/src/api/schema.d.ts', import.meta.url)

const doc = (await openApiDocument()) as OpenAPI3
const ast = await openapiTS(doc, { alphabetize: true })
const header = `/**
 * Generated by \`npm run api:types\` from the server's OpenAPI document (GET /api/v1/openapi.json).
 * Do not edit: change the routes in apps/server and regenerate.
 */

`
await writeFile(out, header + astToString(ast))
console.log(`wrote ${out.pathname}`)
